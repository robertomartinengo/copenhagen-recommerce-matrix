-- GDPR support for lead collection: explicit consent metadata, audit trail,
-- user-requested deletion, and scheduled anonymisation after 12 months.

alter table public.leads
    add column if not exists consent_version text,
    add column if not exists consent_at timestamptz,
    add column if not exists privacy_notice_url text;

create table if not exists public.leads_audit (
    id bigint generated by default as identity primary key,
    action text not null check (action in ('insert', 'update', 'delete', 'anonymize')),
    actor text not null,
    occurred_at timestamptz not null default now(),
    affected_rows integer not null default 1
);

alter table public.leads_audit enable row level security;
revoke all on public.leads_audit from anon, authenticated;

create or replace function public.insert_lead_with_consent(
    p_telegram_user_id bigint,
    p_telegram_username text,
    p_full_name text,
    p_email text,
    p_business_type text,
    p_interested_district text,
    p_consent_version text,
    p_consent_at timestamptz,
    p_privacy_notice_url text,
    p_actor text default 'telegram_bot'
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
    v_lead_id bigint;
begin
    if p_consent_version is null or p_consent_at is null or p_privacy_notice_url is null then
        raise exception 'Explicit consent is required before storing lead data';
    end if;

    insert into public.leads (
        telegram_user_id,
        telegram_username,
        full_name,
        email,
        business_type,
        interested_district,
        consent_version,
        consent_at,
        privacy_notice_url
    )
    values (
        p_telegram_user_id,
        p_telegram_username,
        p_full_name,
        p_email,
        p_business_type,
        p_interested_district,
        p_consent_version,
        p_consent_at,
        p_privacy_notice_url
    )
    returning id into v_lead_id;

    insert into public.leads_audit (action, actor, affected_rows)
    values ('insert', p_actor, 1);

    return v_lead_id;
end;
$$;

create or replace function public.delete_lead_data(
    p_telegram_user_id bigint,
    p_actor text default 'api'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_deleted integer;
begin
    delete from public.leads where telegram_user_id = p_telegram_user_id;
    get diagnostics v_deleted = row_count;

    if v_deleted > 0 then
        insert into public.leads_audit (action, actor, affected_rows)
        values ('delete', p_actor, v_deleted);
    end if;

    return v_deleted;
end;
$$;

create or replace function public.anonymize_leads_older_than(
    p_older_than interval default interval '12 months',
    p_actor text default 'scheduled_anonymization'
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
    v_updated integer;
begin
    update public.leads
    set
        telegram_user_id = null,
        telegram_username = null,
        full_name = null,
        email = null
    where created_at < now() - p_older_than
      and (
          telegram_user_id is not null
          or telegram_username is not null
          or full_name is not null
          or email is not null
      );

    get diagnostics v_updated = row_count;

    if v_updated > 0 then
        insert into public.leads_audit (action, actor, affected_rows)
        values ('anonymize', p_actor, v_updated);
    end if;

    return v_updated;
end;
$$;

revoke all on function public.insert_lead_with_consent(bigint, text, text, text, text, text, text, timestamptz, text, text) from public, anon, authenticated;
revoke all on function public.delete_lead_data(bigint, text) from public, anon, authenticated;
revoke all on function public.anonymize_leads_older_than(interval, text) from public, anon, authenticated;

grant execute on function public.insert_lead_with_consent(bigint, text, text, text, text, text, text, timestamptz, text, text) to service_role;
grant execute on function public.delete_lead_data(bigint, text) to service_role;
grant execute on function public.anonymize_leads_older_than(interval, text) to service_role;
